


import TaskList from './TaskList'; // ייבוא קומפוננטת רשימת המשימות מבן משנה אל קובץ האב
import TaskSummary from './TaskSummary'; // ייבוא קומפוננטת הסיכום מבן משנה אל קובץ האב
import UserInfo from './UserInfo'; // ייבוא קומפוננטת פרטי המשתמש מבן משנה אל קובץ האב

function App() { // הגדרת פונקציית האב הראשית של האפליקציה (הקומפוננטה המרכזית)
  // נתונים סטטיים בלבד לפי דרישת התרגיל
  const username = "ישראל ישראلي"; // הגדרת משתנה סטטי המכיל את שם המשתמש
  const tasks = [ // הגדרת מערך סטטי המכיל את רשימת המשימות והסטטוסים שלהן
    { name: "ללמוד ריאקט", status: "הושלם" }, // משימה ראשונה במערך
    { name: "להכין שיעורי בית", status: "בביצוע" }, // משימה שניה במערך
    { name: "לתרגל קומפוננטות", status: "הושלם" } // משימה שלישית במערך
  ];

  const totalTasks = tasks.length; // חישוב המספר הכולל של המשימות מתוך אורך המערך
  const completedTasks = tasks.filter(task => task.status === "הושלם").length; // סינון המשימות שהושלמו וספירת כמותן

  return ( // הפקודה שמורה לקומפוננטת האב להחזיר את כל מבנה ה-HTML של העמוד לדפדפן
    <div style={{ direction: 'rtl', padding: '20px' }}> // תגית עטיפה ראשית המגדירה כיוון מימין לשאל ומרווח פנימי
      <h1>אתר לניהול משימות</h1> // כותרת ראשית של העמוד
      
      {/* קומפוננטה 3: כותרות ופרטי משתמש */}
      <UserInfo username={username} /> // קריאה לקומפוננטת פרטי המשתמש והעברת שם המשתמש דרך ה-props

      {/* קומפוננטה 1: רשימת משימות */}
      <TaskList tasks={tasks} /> // קריאה לקומפוננטת רשימת המשימות והעברת מערך המשימות דרך ה-props

      {/* קומפוננטה 2: סיכום הכל */}
      <TaskSummary total={totalTasks} completed={completedTasks} /> // קריאה לקומפוננטת הסיכום והעברת סך הכל המשימות והמשימות שהושלמו דרך ה-props
    </div> // סגירת תגית העטיפה הראשית
  ); // סגירת פקודת ההחזרה (return)
} // סגירת גוף פונקציית האב App

export default App; // ייצוא קומפוננטת האב כדי שתוכל לרוץ ולהיטען במערכת (כמו בקובץ main.jsx)