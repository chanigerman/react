



function TaskList(props) { // הגדרת הפונקציה המהווה את הקומפוננטה; מקבלת את נתוני ה-props מבחוץ
  return ( // הפקודה שמורה לקומפוננטה להחזיר את תצוגת ה-HTML לדפדפן
    <div> // תגית עטיפה ראשית המרכזת את כל תוכן הקומפוננטה תחת קורת גג אחת
      <h2>רשימת משימות</h2> // כותרת ראשית שמוצגת בראש הרשימה
      <ul> // פתיחת רשימה לא ממוינת להצגת פריטי המשימות
        {props.tasks.map((task, index) => ( // מעבר באמצעות פונקציית map על כל משימה במערך ה-tasks שהתקבל ב-props
          <li key={index}> // יצירת שורה (פריט) ברשימה עבור כל משימה, עם מפתח ייחודי (key) לפי האינדקס
            {task.name} - סטטוס: {task.status} // הצגת שם המשימה הנוכחית והסטטוס שלה על המסך
          </li> // סגירת תגית פריט הרשימה
        ))} // סגירת פעולת המעבר על המערך
      </ul> // סגירת הרשימה הלא ממוינת
    </div> // סגירת תגית העטיפה הראשית
  ); // סגירת פקודת ההחזרה (return)
} // סגירת גוף הפונקציה

export default TaskList; // ייצוא הקומפוננטה כך שניתן יהיה לייבא ולהשתמש בה בקבצים אחרים כמו App.jsx